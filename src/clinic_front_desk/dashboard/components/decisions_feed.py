def _render_card(card: DecisionCardView) -> str:
    """Render one Decision ``<li>`` with all interpolated text escaped (Req 14.2).

    Mirrors the ``<template>`` in ``web/decisions_feed.html`` so a JS-disabled
    client still sees the same card, and carries ``data-decision-id`` — the
    reconciliation key the JS uses for optimistic removal / real-time add
    (Req 14.5, 14.8). Patient/finding-derived text is HTML-escaped so it cannot
    inject markup.
    """
    return (
        '<li class="decision-card" '
        f'data-decision-id="{html.escape(card.id, quote=True)}" '
        f'data-kind="{html.escape(card.kind, quote=True)}">'
        f'<p class="decision-card__kind" data-field="kind_label">'
        f"{html.escape(card.kind_label)}</p>"
        f'<p class="decision-card__summary" data-field="summary">'
        f"{html.escape(card.summary)}</p>"
        f'<p class="decision-card__action" data-field="recommended_action">'
        f"{html.escape(card.recommended_action)}</p>"
        '<p class="decision-card__support">Supported by '
        f'<span data-field="supporting_record_count">'
        f"{card.supporting_record_count}</span> records</p>"
        '<p class="decision-card__error" data-field="error" role="alert" hidden></p>'
        '<div class="decision-card__controls">'
        f'<button type="button" class="decision-card__approve" '
        f'data-action="{html.escape(card.approve.action, quote=True)}" '
        f'data-decision-id="{html.escape(card.approve.decision_id, quote=True)}">'
        f"{html.escape(card.approve.label)}</button>"
        f'<button type="button" class="decision-card__dismiss" '
        f'data-action="{html.escape(card.dismiss.action, quote=True)}" '
        f'data-decision-id="{html.escape(card.dismiss.decision_id, quote=True)}">'
        f"{html.escape(card.dismiss.label)}</button>"
        "</div>"
        "</li>"
    )


def _card_payload(card: DecisionCardView) -> dict[str, object]:
    """Shape one card for the JSON the JS hydrates from (fields the JS reads)."""
    return {
        "id": card.id,
        "kind": card.kind,
        "kind_label": card.kind_label,
        "summary": card.summary,
        "recommended_action": card.recommended_action,
        "supporting_record_count": card.supporting_record_count,
        "generated_at": card.generated_at,
    }


def _feed_json(view: DecisionsFeedView) -> str:
    """Serialize the view-model as embeddable JSON for JS hydration (Req 14.1).

    ``</`` is escaped so the payload cannot terminate the surrounding
    ``<script>`` element.
    """
    payload = {
        "cards": [_card_payload(card) for card in view.cards],
        "is_empty": view.is_empty,
        "empty_state_message": view.empty_state_message,
        "has_error": view.has_error,
    }
    return json.dumps(payload).replace("</", "<\\/")


def render_decisions_feed(
    feed: DecisionsFeedView | list[Decision],
    *,
    decisions_endpoint: str = DEFAULT_DECISIONS_ENDPOINT,
) -> str:
    """Render the ``DecisionsFeed`` partial to an HTML string (Req 14.1, 14.2, 14.7).

    Builds the view-model (when given a list of Decisions), renders one card per
    open Decision newest-first (Req 14.1) with approve/dismiss controls
    (Req 14.2), toggles the empty-state message when there are none (Req 14.7),
    and embeds the view-model as JSON so the client JS can take over real-time
    add / optimistic removal (Req 14.5, 14.8). All interpolated text is escaped.

    Args:
        feed: A pre-built :class:`DecisionsFeedView` (e.g. an error view from
            :func:`build_decisions_feed_from_result`) or a list of open
            Decisions to shape here.
        decisions_endpoint: Base URL embedded for the client JS to re-fetch the
            rebuilt feed from on a real-time add.

    Returns:
        The rendered HTML partial as a string.
    """
    view = feed if isinstance(feed, DecisionsFeedView) else build_decisions_feed(feed)
    cards_html = "\n    ".join(_render_card(card) for card in view.cards)
    template = _load_template("decisions_feed.html")
    return template.format(
        decisions_endpoint=html.escape(decisions_endpoint, quote=True),
        has_error="true" if view.has_error else "false",
        empty_message=html.escape(view.empty_state_message),
        empty_hidden="" if view.is_empty else " hidden",
        list_hidden=" hidden" if view.is_empty else "",
        cards=cards_html,
        feed_json=_feed_json(view),
    )


